  function translateValue(value) {
    const exact = kk[value];
    if (exact) return exact;
    let translated = value;
    for (const [from, to] of replacements) translated = translated.split(from).join(to);
    return translated;
  }

  function translatedWithWhitespace(value) {
    const start = value.match(/^\s*/)?.[0] ?? "";
    const end = value.match(/\s*$/)?.[0] ?? "";
    const core = value.slice(start.length, value.length - end.length || undefined);
    return `${start}${translateValue(core)}${end}`;
  }

  function translateTextNode(node) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue ?? "");
    const original = originalText.get(node) ?? "";
    const translated = currentLanguage === "kk" ? translatedWithWhitespace(original) : original;
    const withoutTerminalDot = translated.replace(/([^\.\s])\.(\s*)$/, "$1$2");
    if (node.nodeValue !== withoutTerminalDot) node.nodeValue = withoutTerminalDot;
  }

  const attributes = ["placeholder", "aria-label", "title", "alt", "data-label"];

  function translateElement(element) {
    if (!originalAttributes.has(element)) originalAttributes.set(element, {});
    const originals = originalAttributes.get(element);
    for (const attribute of attributes) {
      if (!element.hasAttribute(attribute)) continue;
      if (!(attribute in originals)) originals[attribute] = element.getAttribute(attribute);
      const original = originals[attribute] ?? "";
      const translated = currentLanguage === "kk" ? translateValue(original) : original;
      if (element.getAttribute(attribute) !== translated) element.setAttribute(attribute, translated);
    }
  }

  function translateSubtree(root) {
    if (!root) return;

    if (root.nodeType === Node.TEXT_NODE) {
      const parent = root.parentElement;
      if (parent && !parent.closest("script, style, noscript, [data-language-toggle], [translate='no']") && root.nodeValue?.trim()) {
        translateTextNode(root);
      }
      return;
    }

    if (root.nodeType !== Node.ELEMENT_NODE || root.matches("script, style, noscript, [data-language-toggle], [translate='no']")) return;

    translateElement(root);
    for (const element of root.querySelectorAll("*")) {
      if (!element.closest("script, style, noscript, [data-language-toggle], [translate='no']")) translateElement(element);
    }

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const parent = node.parentElement;
        if (!parent || parent.closest("script, style, noscript, [data-language-toggle], [translate='no']")) return NodeFilter.FILTER_REJECT;
        return node.nodeValue?.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      },
    });

    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(translateTextNode);
  }

  function ensureButton() {
    for (const header of document.querySelectorAll(".kpHeader")) {
      if (header.querySelector(".kpLanguage")) continue;
      const button = document.createElement("button");
      button.type = "button";
      button.className = "kpLanguage";
      button.setAttribute("data-language-toggle", "");
      const cabinet = header.querySelector(".kpCabinet");
      header.insertBefore(button, cabinet);
    }
  }

  function updateButtons() {
    const label = currentLanguage === "ru" ? "ҚАЗ" : "РУС";
    const ariaLabel = currentLanguage === "ru" ? "Қазақ тіліне ауысу" : "Переключить на русский язык";
    const title = currentLanguage === "ru" ? "Қазақша" : "Русский";
    for (const button of document.querySelectorAll("[data-language-toggle]")) {
      if (button.textContent !== label) button.textContent = label;
      if (button.getAttribute("aria-label") !== ariaLabel) button.setAttribute("aria-label", ariaLabel);
      if (button.getAttribute("title") !== title) button.setAttribute("title", title);
    }
  }

  function applyLanguage() {
    if (applying || !document.body) return;
    applying = true;
    try {
      ensureButton();
      document.documentElement.lang = currentLanguage === "kk" ? "kk" : "ru";
      translateSubtree(document.body);
      updateButtons();

      if (!document.documentElement.dataset.originalTitle) document.documentElement.dataset.originalTitle = document.title;
      const originalTitle = document.documentElement.dataset.originalTitle;
      document.title = currentLanguage === "kk" ? translateValue(originalTitle) : originalTitle;
    } finally {
      applying = false;
    }
  }

  function setLanguage(language) {
    currentLanguage = language === "kk" ? "kk" : "ru";
    try {
      localStorage.setItem(STORAGE_KEY, currentLanguage);
    } catch {
      // The language still works for the current page when storage is blocked.
    }
    applyLanguage();
  }

  try {
    currentLanguage = localStorage.getItem(STORAGE_KEY) === "kk" ? "kk" : "ru";
  } catch {
    currentLanguage = "ru";
  }

  document.addEventListener("click", (event) => {
    const button = event.target.closest?.("[data-language-toggle]");
    if (!button) return;
    setLanguage(currentLanguage === "ru" ? "kk" : "ru");
  });

  applyLanguage();

  const mutationObserver = new MutationObserver((mutations) => {
    if (applying) return;

    const addedRoots = new Set();
    for (const mutation of mutations) {
      if (mutation.target.parentElement?.closest("[data-language-toggle]") || mutation.target.closest?.("[data-language-toggle]")) continue;
      for (const node of mutation.addedNodes) {
        const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
        if (element?.closest("script, style, noscript, [data-language-toggle], [translate='no']")) continue;
        addedRoots.add(node);
      }
    }

    if (!addedRoots.size) return;
    applying = true;
    try {
      ensureButton();
      for (const root of addedRoots) translateSubtree(root);
      updateButtons();
    } finally {
      applying = false;
    }
  });
  mutationObserver.observe(document.body, { childList: true, subtree: true });
